// ---------- Report viewer ----------

/**
 * Shows the job's HTML report. The report is generated by the backend from sample-derived
 * text, so it is rendered in an empty sandbox (no scripts, opaque origin). The request is
 * made with the bearer token, which a plain link could not send.
 */
export function ReportDialog({ jobId, open, onClose }: { jobId: number; open: boolean; onClose: () => void }) {
  const [notesDraft, setNotesDraft] = useState("");
  const [notes, setNotes] = useState("");
  const [html, setHtml] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [downloading, setDownloading] = useState(false);
  const [downloadError, setDownloadError] = useState<string | null>(null);

  useEffect(() => {
    if (!open) return;
    const controller = new AbortController();
    setLoading(true);
    setError(null);
    const query = notes ? `&notes=${encodeURIComponent(notes)}` : "";
    fetchText(`/jobs/${jobId}/report?format=html${query}`, controller.signal)
      .then((text) => {
        if (controller.signal.aborted) return;
        setHtml(text);
        setLoading(false);
      })
      .catch((err: unknown) => {
        if (controller.signal.aborted) return;
        setError(errorMessage(err, "The report could not be loaded."));
        setLoading(false);
      });
    return () => controller.abort();
  }, [open, jobId, notes]);

  async function onPdf() {
    setDownloading(true);
    setDownloadError(null);
    try {
      const query = notes ? `&notes=${encodeURIComponent(notes)}` : "";
      await downloadFile(`/jobs/${jobId}/report?format=pdf${query}`, `report_${jobId}.pdf`);
    } catch (err) {
      setDownloadError(errorMessage(err, "The PDF could not be downloaded."));
    } finally {
      setDownloading(false);
    }
  }

  return (
    <Dialog
      open={open}
      onClose={onClose}
      wide
      title={`Analysis report, job #${jobId}`}
      description="Generated by Cerberus from this job's stored results. Optional analyst notes are included in the report."
      footer={
        <>
          <Button variant="ghost" onClick={onPdf} disabled={downloading} icon={Download}>
            {downloading ? "Preparing PDF…" : "Download PDF"}
          </Button>
          <Button variant="secondary" onClick={onClose}>
            Close
          </Button>
        </>
      }
    >
      <form
        onSubmit={(e) => {
          e.preventDefault();
          setNotes(notesDraft.trim());
        }}
        style={{ display: "grid", gap: 12, marginBottom: 14 }}
      >
        <TextField
          label="Analyst notes (optional)"
          hint="Applied when you press Update report."
          value={notesDraft}
          onChange={(e) => setNotesDraft(e.target.value)}
          maxLength={4000}
        />
        <div>
          <Button type="submit" size="sm" variant="secondary">
            Update report
          </Button>
        </div>
      </form>
      {downloadError && (
        <div style={{ marginBottom: 12 }}>
          <Notice tone="err">{downloadError}</Notice>
        </div>
      )}
      {loading && <LoadingBlock label="Loading report" rows={4} height={16} />}
      {!loading && error && <ErrorState message={error} />}
      {!loading && !error && html !== null && (
        <iframe
          className="report-frame"
          title={`Analysis report for job ${jobId}`}
          sandbox=""
          srcDoc={html}
        />
      )}
    </Dialog>
  );
}

// ---------- Run one analysis job ----------

export function RunAnalysisDialog({
  open,
  onClose,
  sampleId,
  onDone,
}: {
  open: boolean;
  onClose: () => void;
  sampleId: number;
  onDone: (job: Job) => void;
}) {
  const formId = useId();
  const [internet, setInternet] = useState<"online" | "offline">("online");
  const [mutex, setMutex] = useState(false);
  const [hostname, setHostname] = useState("");
  const [timeout, setTimeoutValue] = useState("60");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [timeoutError, setTimeoutError] = useState<string | null>(null);

  useEffect(() => {
    if (!open) {
      setBusy(false);
      setError(null);
    }
  }, [open]);

  async function submit(e: FormEvent) {
    e.preventDefault();
    const seconds = Number(timeout);
    if (!Number.isInteger(seconds) || seconds < 1 || seconds > 3600) {
      setTimeoutError("Enter a whole number of seconds from 1 to 3600.");
      return;
    }
    setTimeoutError(null);
    setError(null);
    const conditions: Record<string, unknown> = { internet: internet === "online" };
    if (mutex) conditions.existing_mutex = true;
    if (hostname.trim()) conditions.hostname = hostname.trim();

    setBusy(true);
    try {
      const job = await api.post<Job>("/jobs", {
        sample_id: sampleId,
        conditions,
        timeout_seconds: seconds,
      });
      onDone(job);
    } catch (err) {
      setError(errorMessage(err, "The analysis could not be started."));
    } finally {
      setBusy(false);
    }
  }

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Run analysis"
      description="The run executes synchronously and returns when it finishes. Cerberus does not show progress percentages."
      footer={
        <>
          <Button variant="secondary" onClick={onClose} disabled={busy}>
            Cancel
          </Button>
          <button type="submit" form={formId} className="btn btn-primary" disabled={busy}>
            <Play size={15} aria-hidden="true" />
            {busy ? "Running…" : "Start run"}
          </button>
        </>
      }
    >
      <form id={formId} onSubmit={submit} aria-busy={busy} style={{ display: "grid", gap: 16 }}>
        <SelectField label="Network condition" value={internet} onChange={(e) => setInternet(e.target.value as "online" | "offline")} hint="Changes the environment the simulated executor sees.">
          <option value="online">Online (internet reachable)</option>
          <option value="offline">Offline (internet unreachable)</option>
        </SelectField>
        <CheckField
          label="Pre-create the sample's mutex"
          hint="Simulated condition: the sample finds its mutex already present."
          checked={mutex}
          onChange={(e) => setMutex(e.target.checked)}
        />
        <TextField
          label="Hostname (optional)"
          value={hostname}
          onChange={(e) => setHostname(e.target.value)}
          maxLength={64}
          placeholder="lab-host"
          hint="Leave empty to use the executor default."
        />
        <TextField
          label="Timeout (seconds)"
          value={timeout}
          onChange={(e) => setTimeoutValue(e.target.value)}
          inputMode="numeric"
          error={timeoutError}
        />
        {error && <Notice tone="err">{error}</Notice>}
      </form>
    </Dialog>
  );
}

// ---------- Differential analysis ----------

const VARIATIONS: { id: string; label: string; hint: string; condition: Record<string, unknown> }[] = [
  { id: "offline", label: "Internet unreachable", hint: "Baseline is online; this run sets internet to false.", condition: { internet: false } },
  { id: "mutex", label: "Mutex already present", hint: "Sets existing_mutex to true.", condition: { existing_mutex: true } },
  { id: "host", label: "Different hostname", hint: "Sets hostname to lab-host-2.", condition: { hostname: "lab-host-2" } },
];

export function DifferentialDialog({ open, onClose, sample }: { open: boolean; onClose: () => void; sample: Sample }) {
  const formId = useId();
  const navigate = useNavigate();
  const [selected, setSelected] = useState<string[]>(["offline", "mutex"]);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!open) {
      setBusy(false);
      setError(null);
    }
  }, [open]);

  function toggle(id: string) {
    setSelected((prev) => (prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id]));
  }

  async function submit(e: FormEvent) {
    e.preventDefault();
    const variations = VARIATIONS.filter((v) => selected.includes(v.id)).map((v) => v.condition);
    if (variations.length === 0) {
      setError("Select at least one variation.");
      return;
    }
    setBusy(true);
    setError(null);
    try {
      const result = await api.post<Differential>("/differential", {
        sample_id: sample.id,
        baseline_conditions: { internet: true },
        variations,
      });
      navigate(`/differential/${result.id}`);
    } catch (err) {
      setError(errorMessage(err, "The differential analysis could not be started."));
      setBusy(false);
    }
  }

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Run differential analysis"
      description={`Runs a baseline (online) and one run per selected variation on ${sample.filename}. Each variation changes one condition.`}
      footer={
        <>
          <Button variant="secondary" onClick={onClose} disabled={busy}>
            Cancel
          </Button>
          <button type="submit" form={formId} className="btn btn-primary" disabled={busy || selected.length === 0}>
            {busy ? "Running baseline and variations…" : "Start differential"}
          </button>
        </>
      }
    >
      <form id={formId} onSubmit={submit} aria-busy={busy} style={{ display: "grid", gap: 14 }}>
        <fieldset style={{ border: 0, padding: 0, margin: 0, display: "grid", gap: 12 }}>
          <legend className="field-label" style={{ marginBottom: 4 }}>
            Variations
          </legend>
          {VARIATIONS.map((v) => (
            <CheckField
              key={v.id}
              label={v.label}
              hint={v.hint}
              checked={selected.includes(v.id)}
              onChange={() => toggle(v.id)}
            />
          ))}
        </fieldset>
        {error && <Notice tone="err">{error}</Notice>}
      </form>
    </Dialog>
  );
}

// ---------- Upload ----------

export function UploadDialog({
  open,
  onClose,
  onDone,
}: {
  open: boolean;
  onClose: () => void;
  onDone: (result: SampleUploadResult) => void;
}) {
  const formId = useId();
  const [file, setFile] = useState<File | null>(null);
  const [caseId, setCaseId] = useState("");
  const [tags, setTags] = useState("");
  const [cases, setCases] = useState<Case[]>([]);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!open) {
      setFile(null);
      setCaseId("");
      setTags("");
      setBusy(false);
      setError(null);
      return;
    }
    const controller = new AbortController();
    api
      .get<Case[]>("/cases", controller.signal)
      .then((list) => setCases(list))
      .catch(() => setCases([]));
    return () => controller.abort();
  }, [open]);

  async function submit(e: FormEvent) {
    e.preventDefault();
    if (!file) {
      setError("Choose a file to upload.");
      return;
    }
    setBusy(true);
    setError(null);
    try {
      const form = new FormData();
      form.append("file", file);
      if (caseId) form.append("case_id", caseId);
      if (tags.trim()) form.append("tags", tags.trim());
      const result = await api.upload<SampleUploadResult>("/samples", form);
      onDone(result);
    } catch (err) {
      setError(errorMessage(err, "The upload failed."));
      setBusy(false);
    }
  }

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Upload a sample"
      description="The file is hashed, checked against allowed types, and stored encrypted in quarantine. Identical files are detected as duplicates."
      footer={
        <>
          <Button variant="secondary" onClick={onClose} disabled={busy}>
            Cancel
          </Button>
          <button type="submit" form={formId} className="btn btn-primary" disabled={busy || !file}>
            <Upload size={15} aria-hidden="true" />
            {busy ? "Uploading…" : "Upload"}
          </button>
        </>
      }
    >
      <form id={formId} onSubmit={submit} aria-busy={busy} style={{ display: "grid", gap: 16 }}>
        <div className="field">
          <label htmlFor={`${formId}-file`} className="field-label">
            Sample file
          </label>
          <input
            id={`${formId}-file`}
            type="file"
            className="input"
            style={{ padding: 8 }}
            onChange={(e) => setFile(e.target.files?.[0] ?? null)}
            aria-describedby={`${formId}-file-hint`}
          />
          <span id={`${formId}-file-hint`} className="field-hint">
            The server sets the size limit and accepted file types. Rejected files show the reason here.
          </span>
        </div>
        <SelectField label="Case (optional)" value={caseId} onChange={(e) => setCaseId(e.target.value)}>
          <option value="">No case</option>
          {cases.map((c) => (
            <option key={c.id} value={c.id}>
              {c.name}
            </option>
          ))}
        </SelectField>
        <TextField
          label="Tags (optional)"
          value={tags}
          onChange={(e) => setTags(e.target.value)}
          hint="Comma-separated, for example: phishing, q3-batch"
          maxLength={500}
        />
        {error && <Notice tone="err">{error}</Notice>}
      </form>
    </Dialog>
  );
}

// ---------- Tags ----------

export function TagsDialog({
  open,
  onClose,
  sample,
  onDone,
}: {
  open: boolean;
  onClose: () => void;
  sample: Sample;
  onDone: (sample: Sample) => void;
}) {
  const formId = useId();
  const [value, setValue] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (open) {
      setValue(sample.tags.join(", "));
      setError(null);
      setBusy(false);
    }
  }, [open, sample.tags]);

  async function submit(e: FormEvent) {
    e.preventDefault();
    const tags = value
      .split(",")
      .map((t) => t.trim())
      .filter(Boolean);
    setBusy(true);
    setError(null);
    try {
      const updated = await api.put<Sample>(`/samples/${sample.id}/tags`, { tags });
      onDone(updated);
    } catch (err) {
      setError(errorMessage(err, "Tags could not be saved."));
      setBusy(false);
    }
  }

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Edit tags"
      footer={
        <>
          <Button variant="secondary" onClick={onClose} disabled={busy}>
            Cancel
          </Button>
          <button type="submit" form={formId} className="btn btn-primary" disabled={busy}>
            {busy ? "Saving…" : "Save tags"}
          </button>
        </>
      }
    >
      <form id={formId} onSubmit={submit} style={{ display: "grid", gap: 12 }}>
        <TextField
          label="Tags"
          value={value}
          onChange={(e) => setValue(e.target.value)}
          hint="Comma-separated. Saving replaces the full tag list."
        />
        {error && <Notice tone="err">{error}</Notice>}
      </form>
    </Dialog>
  );
}
